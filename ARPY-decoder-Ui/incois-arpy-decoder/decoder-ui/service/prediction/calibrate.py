"""Calibration artefact: validation-derived uncertainty radii and metrics.

The artefact is generated by ``python -m prediction.validate`` from historical
Ifremer ``_Rtraj.nc`` cycles and contains ONLY aggregate statistics:

* empirical 50 % / 90 % great-circle error radii per method and stratum,
* validation metrics (median / mean / p90 / RMSE / hit rates / sample count),
* a sparse regional/seasonal drift grid (median displacement per 2 deg cell and
  month) used by the prior rung,
* corpus provenance (float count, case count, per-file SHA-256 digest).

No profile or trajectory record is stored, so this is a calibration table, not a
local historical database. If the artefact is missing or lacks an entry for the
selected method and stratum, the engine refuses the prediction instead of
inventing a radius (PART 8).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

CALIBRATION_ENV = "PREDICTION_CALIBRATION_PATH"
CALIBRATION_FILENAME = "prediction_calibration.json"

#: Stage-1 keeps its OWN artefact so the Stage-0 baseline file stays byte-identical
#: and each stage's radii are derived from its own historical errors (STAGE-1
#: requirement: never reuse Stage-0 R50/R90 for Stage-1).
CALIBRATION_STAGE1_ENV = "PREDICTION_CALIBRATION_STAGE1_PATH"
CALIBRATION_STAGE1_FILENAME = "prediction_calibration_stage1.json"

METHOD_HISTORY_PRIOR = "history_prior"
METHOD_TRAJECTORY = "trajectory_extrapolation"
METHOD_REGIONAL_PRIOR = "regional_prior"
METHOD_PERSISTENCE = "persistence"
#: Stage-1 cycle-scale step methods (see prediction/cycle_step.py).
METHOD_CYCLE_WINDOW = "cycle_window"
METHOD_CYCLE_WINDOW_PRIOR = "cycle_window_prior"
METHOD_CYCLE_MEDIAN = "cycle_median"
METHOD_CYCLE_MEDIAN_PRIOR = "cycle_median_prior"
STAGE1_METHODS = (
    METHOD_CYCLE_WINDOW,
    METHOD_CYCLE_WINDOW_PRIOR,
    METHOD_CYCLE_MEDIAN,
    METHOD_CYCLE_MEDIAN_PRIOR,
)

METHOD_CURRENT_ASSISTED = "current_assisted"
METHOD_PHYSICS = "physics_lagrangian"
METHOD_ML_RESIDUAL = "ml_residual"

#: UI terminology required by the feature request.
METHOD_LABELS: dict[str, str] = {
    METHOD_HISTORY_PRIOR: "History + Prior",
    METHOD_TRAJECTORY: "Trajectory Extrapolation",
    METHOD_REGIONAL_PRIOR: "Regional / Seasonal Prior",
    METHOD_PERSISTENCE: "Persistence",
    METHOD_CURRENT_ASSISTED: "Current-Assisted",
    METHOD_PHYSICS: "Physics / Lagrangian",
    METHOD_ML_RESIDUAL: "ML Residual Correction",
    # Stage-1 labels state the stage so a validation run can never present a
    # Stage-1 prediction as the Stage-0 baseline (or the reverse).
    METHOD_CYCLE_WINDOW: "Cycle-Scale Window (Stage-1)",
    METHOD_CYCLE_WINDOW_PRIOR: "Cycle-Scale Window + Prior (Stage-1)",
    METHOD_CYCLE_MEDIAN: "Cycle-Scale Median (Stage-1)",
    METHOD_CYCLE_MEDIAN_PRIOR: "Cycle-Scale Median + Prior (Stage-1)",
}

#: Stage labels for the payload/UI, so the baseline is never overwritten invisibly.
STAGE_STAGE0 = "stage0"
STAGE_STAGE1 = "stage1"
STAGE_LABELS: dict[str, str] = {
    STAGE_STAGE0: "Stage-0 baseline (last-hop step)",
    STAGE_STAGE1: "Stage-1 cycle-scale step",
}

#: Documented fallback weight, overridden by the calibrated value when present.
DEFAULT_BLEND_WEIGHT_ON_PRIOR = 0.2


def default_calibration_path() -> Path:
    override = os.environ.get(CALIBRATION_ENV)
    if override:
        return Path(override)
    try:
        from event_bus import DATA_DIR  # local import: avoids a hard import cycle

        candidate = Path(DATA_DIR) / "fleet_status" / CALIBRATION_FILENAME
        if candidate.is_file():
            return candidate
    except Exception:
        pass
    return Path(__file__).resolve().parents[2] / "data" / "fleet_status" / CALIBRATION_FILENAME


@dataclass(frozen=True)
class Radii:
    r50_km: float
    r90_km: float
    samples: int
    basis: str


@dataclass
class Calibration:
    """Validated uncertainty + metrics for the prediction methods."""

    version: int = 0
    generated_at: str | None = None
    blend_weight_on_prior: float = DEFAULT_BLEND_WEIGHT_ON_PRIOR
    default_interval_days: float = 10.0
    methods: dict[str, Any] = field(default_factory=dict)
    prior_grid: dict[str, Any] = field(default_factory=dict)
    corpus: dict[str, Any] = field(default_factory=dict)
    path: str | None = None
    load_error: str | None = None
    stage: str = STAGE_STAGE0

    @property
    def available(self) -> bool:
        return bool(self.methods)


def default_stage1_calibration_path() -> Path:
    """Where the Stage-1 artefact lives when not overridden by the environment."""
    override = os.environ.get(CALIBRATION_STAGE1_ENV)
    if override:
        return Path(override)
    try:
        from event_bus import DATA_DIR  # local import: avoids a hard import cycle

        candidate = Path(DATA_DIR) / "fleet_status" / CALIBRATION_STAGE1_FILENAME
        if candidate.is_file():
            return candidate
    except Exception:
        pass
    return Path(__file__).resolve().parents[2] / "data" / "fleet_status" / CALIBRATION_STAGE1_FILENAME


def load_stage1_calibration(path: Path | None = None) -> Calibration:
    """The Stage-1 artefact, loaded with the same schema as the Stage-0 one."""
    return load_calibration(path if path is not None else default_stage1_calibration_path())


def load_calibration(path: Path | None = None) -> Calibration:
    target = Path(path) if path is not None else default_calibration_path()
    try:
        raw = json.loads(target.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return Calibration(path=str(target), load_error="calibration artefact not present")
    except Exception as exc:  # pragma: no cover - defensive
        return Calibration(path=str(target), load_error=f"{type(exc).__name__}: {exc}")
    if not isinstance(raw, dict):
        return Calibration(path=str(target), load_error="calibration artefact is not an object")
    cells = raw.get("prior_grid") or {}
    return Calibration(
        version=int(raw.get("version") or 0),
        generated_at=raw.get("generated_at"),
        blend_weight_on_prior=float(
            raw.get("blend_weight_on_prior", DEFAULT_BLEND_WEIGHT_ON_PRIOR)
        ),
        default_interval_days=float(raw.get("default_interval_days", 10.0)),
        methods=raw.get("methods") or {},
        prior_grid=cells if isinstance(cells, dict) else {},
        corpus=raw.get("corpus") or {},
        path=str(target),
        stage=str(raw.get("stage") or STAGE_STAGE0),
    )


def _entry(method: dict[str, Any], region: str | None, cycle_class: str | None) -> dict | None:
    strata = method.get("strata")
    if isinstance(strata, dict):
        if region and cycle_class:
            hit = strata.get(f"{region}|{cycle_class}")
            if hit:
                return hit
        if region:
            hit = strata.get(f"{region}|*")
            if hit:
                return hit
    default = method.get("default")
    return default if isinstance(default, dict) else None


def radii_for(
    calibration: Calibration,
    method_key: str,
    region: str | None = None,
    cycle_class: str | None = None,
) -> Radii | None:
    """Validated radii for a method + stratum, or None (never a guessed radius)."""
    method = calibration.methods.get(method_key)
    if not isinstance(method, dict):
        return None
    for current_class in (cycle_class, "*"):
        entry = _entry(method, region, current_class if current_class != "*" else None)
        if not entry:
            continue
        r50, r90 = entry.get("r50_km"), entry.get("r90_km")
        samples = int(entry.get("n") or 0)
        if r50 is None or r90 is None or samples <= 0:
            continue
        basis = f"{METHOD_LABELS.get(method_key, method_key)}"
        if region:
            basis += f" · {region}"
        if cycle_class:
            basis += f" · {cycle_class} cycle"
        if entry.get("scope"):
            basis += f" · {entry['scope']}"
        return Radii(float(r50), float(r90), samples, basis)
    return None


def metrics_for(
    calibration: Calibration,
    method_key: str,
    region: str | None = None,
    cycle_class: str | None = None,
) -> dict[str, Any] | None:
    method = calibration.methods.get(method_key)
    if not isinstance(method, dict):
        return None
    entry = _entry(method, region, cycle_class)
    metrics = entry.get("metrics") if isinstance(entry, dict) else None
    return metrics if isinstance(metrics, dict) else None
